# 从 WebView2.h 里抽取所有 MIDL_INTERFACE 的 GUID，生成 src/gui/webview2_iids.h
# 这样代码里用 kIID_XXX 常量，不依赖 MSVC 的 __uuidof，MinGW/GCC 也能编译。

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$header = Join-Path $root "_deps\webview2\build\native\include\WebView2.h"
$outFile = Join-Path $root "src\gui\webview2_iids.h"

if (-not (Test-Path $header)) {
  throw "找不到 $header，请先运行 tools/fetch_webview2.ps1"
}

$text = Get-Content -LiteralPath $header -Raw
$rx = [regex]'MIDL_INTERFACE\("([0-9a-fA-F\-]{36})"\)\s*\r?\n\s*([A-Za-z0-9_]+)\s*:'
$matches = $rx.Matches($text)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('// AUTO-GENERATED by tools/gen_iids.ps1 from Microsoft.Web.WebView2 WebView2.h')
[void]$sb.AppendLine('// Do not edit by hand.')
[void]$sb.AppendLine('#include <guiddef.h>')
[void]$sb.AppendLine('')

foreach ($m in $matches) {
  $hex = $m.Groups[1].Value.ToLower().Replace('-', '')
  $name = $m.Groups[2].Value
  $bytes = @()
  for ($i = 0; $i -lt 32; $i += 2) { $bytes += ("0x" + $hex.Substring($i, 2)) }
  $p1 = "0x" + $hex.Substring(0, 8)
  $p2 = "0x" + $hex.Substring(8, 4)
  $p3 = "0x" + $hex.Substring(12, 4)
  $rest = ($bytes[8..15] -join ', ')
  [void]$sb.AppendLine("static const GUID kIID_$name = {$p1, $p2, $p3, {$rest}};")
}

Set-Content -LiteralPath $outFile -Value $sb.ToString() -Encoding utf8
Write-Host ("已生成 {0}（{1} 个接口）" -f $outFile, $matches.Count) -ForegroundColor Green
